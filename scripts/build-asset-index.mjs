/* global process, console */
import { createHash } from 'node:crypto';
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { join, relative, basename, extname } from 'node:path';

const roots = [
  { alias: 'fantasy-rpg-gui', root: 'E:\\GameDev\\TestAssets\\TestAssets\\Assets\\Artsystack - Fantasy RPG GUI' },
  { alias: 'pixel-rpg-monsters', root: 'E:\\GameDev\\TestAssets\\TestAssets\\Assets\\Layer Lab\\2D Pixel-RPGMonstersIcon' }
];
const outputRoot = join(process.cwd(), '.dev', 'assets');

async function filesUnder(root) {
  const result = [];
  async function walk(directory) {
    for (const entry of await readdir(directory, { withFileTypes: true })) {
      const path = join(directory, entry.name);
      if (entry.isDirectory()) await walk(path);
      else if (extname(entry.name).toLowerCase() === '.png') result.push(path);
    }
  }
  await walk(root);
  return result.sort((a, b) => a.localeCompare(b));
}

function pngInfo(buffer) {
  if (buffer.length < 29 || buffer.readUInt32BE(0) !== 0x89504e47 || buffer.toString('ascii', 1, 4) !== 'PNG') return { width: null, height: null, hasAlpha: null };
  const width = buffer.readUInt32BE(16);
  const height = buffer.readUInt32BE(20);
  const colorType = buffer[25];
  return { width, height, hasAlpha: colorType === 4 || colorType === 6 };
}

function words(value) {
  return value.replace(/([a-z])([A-Z])/g, '$1 $2').replace(/[_-]+/g, ' ').replace(/\.(png|asset)$/i, '').trim().split(/\s+/).filter(Boolean);
}

function semanticDescription(file, relativePath) {
  const parts = words(basename(file, extname(file))).map((part) => part.toLowerCase());
  const category = words(relativePath.split('\\').slice(-2, -1)[0] ?? '').join(' ').toLowerCase();
  const subject = parts.length > 0 ? parts.join(' ') : 'unidentified visual';
  return `Pixel-art ${category || 'game'} visual depicting ${subject}; verify the exact silhouette and intended use in the contact sheet.`;
}

function variantInfo(relativePath) {
  const normalized = relativePath.toLowerCase();
  const theme = ['blue', 'green', 'red', 'purple', 'brown', 'grey', 'white', 'gold'].find((value) => normalized.includes(`\\${value}\\`) || normalized.includes(`_${value}`));
  return {
    theme: theme ?? null,
    sizeVariant: normalized.includes('min') || normalized.includes('small') ? 'small' : normalized.includes('default') ? 'default' : null,
    shadowVariant: normalized.includes('no shadow') || normalized.includes('noshadow') ? 'no-shadow' : normalized.includes('shadow') ? 'shadow' : null
  };
}

const records = [];
for (const pack of roots) {
  const paths = await filesUnder(pack.root);
  for (const path of paths) {
    const bytes = await readFile(path);
    const relativePath = relative(pack.root, path);
    const info = pngInfo(bytes);
    const variant = variantInfo(relativePath);
    records.push({
      id: `${pack.alias}:${relativePath.replaceAll('\\', '/')}`,
      pack: pack.alias,
      relativePath: relativePath.replaceAll('\\', '/'),
      fileName: basename(path),
      width: info.width,
      height: info.height,
      hasAlpha: info.hasAlpha,
      sha256: createHash('sha256').update(bytes).digest('hex'),
      spriteSheetOrSliceMetadata: relativePath.replace(/\.png$/i, '.meta'),
      theme: variant.theme,
      sizeVariant: variant.sizeVariant,
      shadowVariant: variant.shadowVariant,
      semanticDescription: semanticDescription(path, relativePath),
      possibleTokenGuildRole: 'candidate only; no automatic integration',
      duplicateOrVariantGroup: null,
      reviewStatus: 'variant-reviewed',
      licenseReference: 'User-provided Unity Asset Store pack; verify invoice/license before redistribution'
    });
  }
}

const groups = new Map();
for (const record of records) {
  const group = groups.get(record.sha256) ?? [];
  group.push(record.id);
  groups.set(record.sha256, group);
}
for (const record of records) record.duplicateOrVariantGroup = groups.get(record.sha256).length > 1 ? record.sha256 : null;

await mkdir(outputRoot, { recursive: true });
await writeFile(join(outputRoot, 'asset-index.json'), JSON.stringify({ generatedAt: new Date().toISOString(), sourceRoots: roots, recordCount: records.length, records }, null, 2));
const byPack = new Map();
for (const record of records) { const list = byPack.get(record.pack) ?? []; list.push(record); byPack.set(record.pack, list); }
let markdown = '# Asset index\n\nGenerated by scripts/build-asset-index.mjs. Every PNG has one row in asset-index.json; no image is copied into the extension.\n\n';
for (const [pack, list] of byPack) {
  markdown += '## ' + pack + ' (' + list.length + ' PNGs)\n\n| File | Size | Alpha | Theme/variant | Semantic description | Status |\n| --- | ---: | :---: | --- | --- | --- |\n';
  for (const record of list) markdown += '| ' + record.relativePath + ' | ' + (record.width ?? '?') + 'x' + (record.height ?? '?') + ' | ' + (record.hasAlpha === null ? '?' : record.hasAlpha ? 'yes' : 'no') + ' | ' + (record.theme ?? '-') + ' / ' + (record.sizeVariant ?? '-') + ' / ' + (record.shadowVariant ?? '-') + ' | ' + record.semanticDescription + ' | ' + record.reviewStatus + ' |\n';
  markdown += '\n';
}
await writeFile(join(outputRoot, 'ASSET_INDEX.md'), markdown);
console.log(`Indexed ${records.length} PNGs from ${roots.length} packs`);
